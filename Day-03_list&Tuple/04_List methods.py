#list method

#it short value from list
print(".sort value from list")
list1=[1,5,3,7,10,56,5]
list1.sort()   # .sort() function is used to sort the value from list
print(list1.count(5))
print(list1,"\n")

#adds value 98 at the end of the list
print(".append adds value at the end of the list")
list2=[1,5,3,7,10,56]
list2.append(98)
print(list2,"\n")

#reverse the vlues of the list
print(".reverse the vlues of the list")
list3=[1,5,3,7,10,56]
list3.reverse()
print(list3,"\n")

#remove the value using index position 2 from list
print(".pop remove the value using index position 2 from list")
list4=[1,5,3,7,10,56]
list4.pop(2)
print(list4,"\n")

#remove the value 10 from list
print(".remove the value 10 from list")
list5=[1,5,3,7,10,56]
list5.remove(10)
print(list5,"\n")

