#string slicing

letter1="dear sir rohit thanks you"

print(letter1[:])   #this returns entire value
print(letter1[0:])  #this also returns entire value
print(letter1[0:10]) #this returns value start from 0th position to 10th but not include 10th value 
print(letter1[2:])   #this returns value start from including 2th position values to end 
print(letter1[0:23]) #this returns value start from 0th position to 25th but not include 25th value 
print(letter1[5:18]) #this returns value from 5th position to 18th not include 18th value 


